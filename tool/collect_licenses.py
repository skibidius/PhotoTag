#!/usr/bin/env python3
"""Collect the licenses of everything bundled with PhotoTag.

Reads the resolved pub dependencies, the Flutter SDK, Material Icons and the
bundled font licenses, then writes THIRD_PARTY_LICENSES.md.

Usage:
    python3 tool/collect_licenses.py
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FLUTTER = Path(os.path.realpath(shutil.which("flutter") or "flutter")).parent.parent
OUT = ROOT / "THIRD_PARTY_LICENSES.md"

HEADER = """# Third-party licenses

PhotoTag itself is proprietary — see [LICENSE](LICENSE). This file lists the
third-party components used by the app and its build tooling, and the licenses
they are used under.

The same license texts are available in the app:
**Settings → About → Open source licenses**.

_Generated by `tool/collect_licenses.py`._
"""


def _read_license(base: Path) -> str | None:
    for name in (
        "LICENSE",
        "LICENSE.md",
        "LICENSE.txt",
        "COPYING",
        "COPYING.md",
        "COPYING.txt",
    ):
        path = base / name
        if path.is_file():
            return path.read_text(encoding="utf-8", errors="replace")
    for path in sorted(base.glob("LICENSE*")):
        if path.is_file():
            return path.read_text(encoding="utf-8", errors="replace")
    return None


def main() -> None:
    raw = subprocess.check_output(
        ["flutter", "pub", "deps", "--json"],
        cwd=ROOT,
        text=True,
    )
    deps = json.loads(raw)

    groups: dict[str, dict[str, object]] = {}

    def add(label: str, text: str) -> None:
        text = text.strip()
        if not text:
            return
        digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
        entry = groups.setdefault(digest, {"text": text, "labels": []})
        entry["labels"].append(label)  # type: ignore[union-attr]

    for package in deps.get("packages", []):
        if package.get("source") != "hosted":
            continue
        name = package["name"]
        version = package["version"]
        base = (
            Path.home()
            / ".pub-cache"
            / "hosted"
            / "pub.dev"
            / f"{name}-{version}"
        )
        license_text = _read_license(base)
        if license_text:
            add(f"{name} {version}", license_text)
        else:
            print(f"warning: no LICENSE for {name} {version}")

    flutter_license = FLUTTER / "LICENSE"
    if flutter_license.is_file():
        add("Flutter SDK", flutter_license.read_text(encoding="utf-8", errors="replace"))

    material_license = (
        FLUTTER
        / "bin"
        / "cache"
        / "artifacts"
        / "material_fonts"
        / "MaterialIcons_LICENSE.txt"
    )
    if material_license.is_file():
        add(
            "Material Icons",
            material_license.read_text(encoding="utf-8", errors="replace"),
        )

    add(
        "Google Sans (bundled font)",
        (ROOT / "assets" / "licenses" / "GoogleSans-OFL.txt").read_text(
            encoding="utf-8"
        ),
    )
    add(
        "Roboto Mono (bundled font)",
        (ROOT / "assets" / "licenses" / "RobotoMono-OFL.txt").read_text(
            encoding="utf-8"
        ),
    )

    def license_name(text: str) -> str:
        lower = text.lower()
        if "sil open font license" in lower:
            return "SIL Open Font License 1.1"
        if "apache license" in lower:
            return "Apache License 2.0"
        if "mit license" in lower or "permission is hereby granted, free of charge" in lower:
            return "MIT License"
        if "redistribution and use in source and binary forms" in lower:
            if "neither the name" in lower:
                return "BSD 3-Clause License"
            return "BSD 2-Clause License"
        if "mozilla public license" in lower:
            return "Mozilla Public License"
        first = text.splitlines()[0] if text else "License"
        return first.strip()

    def sort_key(item: tuple[str, dict[str, object]]) -> tuple[str, str]:
        text = str(item[1]["text"])
        return (license_name(text).lower(), str(item[1]["labels"]))

    lines: list[str] = [HEADER.strip(), ""]
    for _, entry in sorted(groups.items(), key=sort_key):
        labels = sorted(str(label) for label in entry["labels"])  # type: ignore[union-attr]
        heading = license_name(str(entry["text"]))
        if labels:
            heading += " — " + labels[0]
        lines.append("## " + heading)
        lines.append("")
        lines.append("Applies to: " + ", ".join(labels))
        lines.append("")
        lines.append("```text")
        lines.append(str(entry["text"]))
        lines.append("```")
        lines.append("")

    OUT.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
